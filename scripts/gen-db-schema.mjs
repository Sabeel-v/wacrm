// Generates src/lib/db/schema.generated.ts from d1/migrations/*.sql.
//
//   npm run db:gen-schema          (run after adding a migration)
//
// Applies the migrations to an in-memory SQLite (node:sqlite) and records,
// per table: columns with a value kind (text | integer | real | boolean |
// json) and foreign keys. The D1 query engine uses this to convert values
// (0/1 → boolean, JSON text → objects) and to resolve PostgREST-style
// embeds such as `contact:contacts(*)`.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { DatabaseSync } from 'node:sqlite'

const MIGRATIONS_DIR = 'd1/migrations'
const OUT = 'src/lib/db/schema.generated.ts'

const db = new DatabaseSync(':memory:')
db.exec('PRAGMA foreign_keys = ON;')
for (const f of readdirSync(MIGRATIONS_DIR).filter((f) => f.endsWith('.sql')).sort()) {
  db.exec(readFileSync(join(MIGRATIONS_DIR, f), 'utf8'))
}

const tables = db
  .prepare(
    `SELECT name, sql FROM sqlite_schema
     WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '%_fts%' AND name NOT LIKE 'd1_%'
     ORDER BY name`,
  )
  .all()

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

const out = {}
for (const { name, sql } of tables) {
  const columns = {}
  for (const c of db.prepare(`SELECT * FROM pragma_table_info(?)`).all(name)) {
    const col = esc(c.name)
    let kind = 'text'
    const t = String(c.type).toUpperCase()
    if (t.includes('INT')) kind = 'integer'
    else if (t.includes('REAL')) kind = 'real'
    if (new RegExp(`CHECK\\s*\\(\\s*${col}\\s+IN\\s*\\(\\s*0\\s*,\\s*1\\s*\\)\\s*\\)`, 'i').test(sql)) kind = 'boolean'
    if (new RegExp(`json_valid\\(\\s*${col}\\s*\\)`, 'i').test(sql)) kind = 'json'
    columns[c.name] = kind
  }
  const foreignKeys = db
    .prepare(`SELECT * FROM pragma_foreign_key_list(?)`)
    .all(name)
    .map((fk) => ({ column: fk.from, references: fk.table, referencedColumn: fk.to ?? 'id' }))
  out[name] = { columns, foreignKeys }
}

const body = `// GENERATED by scripts/gen-db-schema.mjs from d1/migrations. Do not edit.
// Regenerate with: npm run db:gen-schema

export type ColumnKind = 'text' | 'integer' | 'real' | 'boolean' | 'json'

export interface ForeignKey {
  column: string
  references: string
  referencedColumn: string
}

export interface TableMeta {
  columns: Record<string, ColumnKind>
  foreignKeys: ForeignKey[]
}

export const SCHEMA: Record<string, TableMeta> = ${JSON.stringify(out, null, 2)}
`
writeFileSync(OUT, body)
console.log(`Wrote ${OUT}: ${Object.keys(out).length} tables.`)
